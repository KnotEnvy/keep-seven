  if (e.source && fs.existsSync(path.join(ROOT, e.source))) {
    console.error(`--reset ${id}: its source script ${e.source} exists, so the build makes it from that script. Remove or rename the script first (a reset deletes the final file and regenerates the placeholder).`);
    process.exit(2);
  }
