// node tools/build-assets.mjs [--only <id|owner|piece>[,...]] [--placeholders] [--reset <id>[,...]] [--force] [--jobs n] [--manifest overlay.json] [--verbose] [--allow-stale-lightmap]
//
// THE ONE COMMAND (ARCHITECTURE 7.1). `npm run assets` runs it.
//
//   textures -> props, weapons, enemies, boss -> zones -> late bakes -> optimise -> check
//
//   * an item with a source script is built from it:  tools/blender.sh ... -P <source> -- --out <raw path> --seed 1
//     (a `.mjs` source, e.g. tools/gen_fx_atlas.mjs for tx_fx / tx_noise, is run as `node <source> --out blender/export/tex`);
//   * an item WITHOUT a source script is a placeholder: left alone, or (re)generated by blender/placeholders.py when
//     --placeholders is given. A placeholder never replaces a final file;
//   * --reset <id>[,...] is the way BACK from a scripted asset to its placeholder: for an id whose source script does not
//     exist (you removed or renamed it) it deletes the final raw export, its .deps.json, the shipped file and the stamp,
//     then regenerates the placeholder (as `--placeholders --only <id>`). It refuses an id whose script still exists;
//   * a lightmap whose `source` is a zone script is that zone's by-product (bake.save_lightmap writes it). A script whose
//     meshes point at such a lightmap (extra `lightmap` / `lightLayer`) and which did NOT write it in the same run FAILS:
//     the new GLB carries a new UV1 atlas and would sample a stale or placeholder lightmap. --allow-stale-lightmap ships
//     it anyway (iterating on geometry with the bake switched off) and says so on the asset's line;
//   * zones are built after everything else and are rebuilt when the raw export of a prop they embedded changes;
//   * every raw export is optimised into public/assets and checked against the manifest (tools/check-glb.mjs).
//
// Outputs newer than their inputs are skipped. "Inputs" (compared by content hash, blender/export/.stamp/):
//   * the source script, every blender/lib/**/*.py, design/*.json (and blender/tex/*.py for shared textures);
//   * every project module the script imported last time (a helper beside it: `import common`), recorded by
//     export.export_asset in <raw>.deps.json. A helper that is not imported (read as data, exec'd) is NOT seen: use --force;
//   * the ENTRIES of the texture tables (blender/lib/palette.json, tx_*_trim.json, mask_regions.json) the script read
//     through lib.manifest: an appended palette cell or mask region rebuilds nothing, a changed one rebuilds its users;
//   * for zones, the raw exports of the props they embedded;
//   * a lightmap with a bake script of its own (lm_surface <- bake_surface.py, a "late" item run after the zones) is tracked
//     the same way: bake.save_lightmap writes <raw png>.deps.json (imported helper modules, embedded props). When an asset
//     that points at such a lightmap is rebuilt and the lightmap is stale but not part of the run, the run prints
//     `STALE <lightmap>` with the command that builds them together and exits 1 (--allow-stale-lightmap: exit 0).
// NOTHING IS SHIPPED UNTIL IT PASSES: Blender writes under temporary names, the optimiser writes a temporary file beside
// the target, check-glb judges that file, and only then are the raw export, its lightmaps and the shipped files renamed
// into place together. A FAILED item leaves the previous raw export and shipped file exactly as they were.
// --only takes asset ids, texture ids, manifest owners (props_mech, env_interior, render ...) or pieces (art-props).
// One line per item: built / skipped / kept / FAILED with the reason. The full Blender log of each item is in
// blender/export/.logs/<id>.log; lines of it that start with WARNING (bake warnings: buried vertices, double-lit faces,
// a chunk over its share) are counted on the item's line, "(2 warnings: see <log>)", and printed in full by --verbose.
// Exit code 1 on any failure.
// Safe to run by several people at once on different owners: every file is written under a temporary name and renamed,
// and an item being built by another run is waited for, not built twice.
